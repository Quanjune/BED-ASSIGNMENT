// docs/index.js
// Builds the OpenAPI 3.0 document that Swagger UI renders at /api-docs.
//
// WHAT SWAGGER IS, IN ONE PARAGRAPH
// An API is invisible: you cannot look at a URL and know what it accepts or
// returns. OpenAPI (formerly called Swagger) is a standard way to write that
// down in a machine-readable format, and Swagger UI turns that description
// into a web page where every endpoint is listed, documented, and can be
// called straight from the browser - no Postman needed.
//
// HOW THIS FILE WORKS
// It reads EVERY .js file in paths/ and merges them together. Nobody has to
// edit this file to document a new feature - you just add your own file to
// paths/ and it appears on the page. That is deliberate: if all five of us
// had to edit the same two lines here, every branch would conflict.
//
// >>> ADDING YOUR OWN ENDPOINTS? Read ./README.md - do NOT edit this file. <<<

const fs = require("fs");
const path = require("path");
const { securitySchemes, schemas: sharedSchemas, responses } = require("./components");

const PATHS_DIR = path.join(__dirname, "paths");

// Load every feature file. Alphabetical, except login.js is pinned first so
// the "get a token" step sits at the top of the page where people look.
const files = fs
  .readdirSync(PATHS_DIR)
  .filter((f) => f.endsWith(".js"))
  .sort((a, b) => (a === "login.js" ? -1 : b === "login.js" ? 1 : a.localeCompare(b)));

const tags = [];
const paths = {};
const featureSchemas = {};
const pathOwner = {}; // url -> the file that documented it, for the error below

for (const file of files) {
  const mod = require(path.join(PATHS_DIR, file));

  // Two shapes are accepted, so a file that only defines paths still works:
  //   module.exports = { tag, schemas, paths }   <- preferred
  //   module.exports = { "/api/...": { get: ... } }
  const isWrapped = mod && typeof mod === "object" && mod.paths;
  const featurePaths = isWrapped ? mod.paths : mod;

  if (isWrapped && mod.tag) tags.push(mod.tag);
  if (isWrapped && mod.schemas) Object.assign(featureSchemas, mod.schemas);

  // A duplicate URL would silently overwrite the earlier one, which is a
  // horrible thing to debug - fail loudly at startup instead.
  for (const url of Object.keys(featurePaths)) {
    if (paths[url]) {
      throw new Error(
        `Duplicate path "${url}" in backend/docs/paths/: documented in both ` +
          `${pathOwner[url]} and ${file}. Keep it in one of them.`
      );
    }
    paths[url] = featurePaths[url];
    pathOwner[url] = file;
  }
}

const openApiDocument = {
  openapi: "3.0.3",

  info: {
    title: "Hawkers API",
    version: "1.0.0",
    description:
      "REST API for the Hawkers hawker-centre management system " +
      "(Back-End Development assignment).\n\n" +
      "### Trying a protected endpoint\n" +
      "1. Run **POST /api/auth/login** under *Getting a token* below.\n" +
      "2. Copy the `accessToken` out of the response.\n" +
      "3. Click **Authorize** (top right), paste the token, press Authorize.\n" +
      "4. Every 🔒 endpoint will now work from this page.\n\n" +
      "### What the status codes mean here\n" +
      "- **400** the request body or a parameter failed validation\n" +
      "- **401** no token was sent, or it is missing/expired\n" +
      "- **403** logged in, but this role (or this user) may not do it\n" +
      "- **404** no record with that id\n" +
      "- **409** a conflict, e.g. an email or promo code already in use\n\n" +
      "*Groups are added by each feature owner - see `backend/docs/README.md`.*",
  },

  servers: [
    { url: "http://localhost:3000", description: "Local development server" },
  ],

  tags,

  // Applied to every operation unless it sets its own `security`.
  // Public endpoints override it with `security: []`.
  security: [{ bearerAuth: [] }],

  paths,

  components: {
    securitySchemes,
    schemas: { ...sharedSchemas, ...featureSchemas },
    responses,
  },
};

module.exports = openApiDocument;
